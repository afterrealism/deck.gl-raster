/**
 * Named matplotlib-style color ramps as 256-entry RGBA8 lookup tables.
 *
 * Advanced users can introspect these directly, e.g. to validate ramp data
 * or build a custom `Texture` with different sampler options than
 * `createColormapTexture` provides.
 */
export const RAMPS: Record<ColormapName, Uint8Array> = {
  viridis: VIRIDIS_DATA,
  magma: MAGMA_DATA,
  plasma: PLASMA_DATA,
  turbo: TURBO_DATA,
  terrain: TERRAIN_DATA,
};

/**
 * Create a 256×1 RGBA8 `Texture` suitable for the `Colormap` shader module.
 *
 * Accepts either:
 * - A named ramp from {@link RAMPS} — viridis/magma/plasma/turbo/terrain.
 * - A custom `Uint8Array` of exactly `256 * 4` bytes (RGBA8). Use this for
 *   site-specific ramps without having to call `device.createTexture`
 *   yourself.
 *
 * The returned texture uses `linear` filtering and `clamp-to-edge` address
 * modes — appropriate for continuous data ramps.
 *
 * @throws {Error} if `name` is not a known ColormapName
 * @throws {Error} if a `Uint8Array` is provided with the wrong length
 */
export function createColormapTexture(
  device: Device,
  name: ColormapName | Uint8Array,
): Texture {
  let data: Uint8Array;

  if (name instanceof Uint8Array) {
    if (name.length !== RAMP_BYTES) {
      throw new Error(
        `createColormapTexture: custom Uint8Array must be exactly ${RAMP_BYTES} bytes (256 RGBA8 entries). Got ${name.length}.`,
      );
    }
    data = name;
  } else {
    const ramp = RAMPS[name];
    if (!ramp) {
      throw new Error(
        `Unknown colormap: ${name}. Expected one of: ${Object.keys(RAMPS).join(", ")}`,
      );
    }
    data = ramp;
  }

  return device.createTexture({
    data,
    format: "rgba8unorm",
    width: RAMP_LENGTH,
    height: 1,
    sampler: {
      minFilter: "linear",
      magFilter: "linear",
      addressModeU: "clamp-to-edge",
      addressModeV: "clamp-to-edge",
    },
  });
}
